// Builds RoleLoot/Data.lua (which boss drops each piece of gear, or which quest
// gives it) from the MIT-licensed wow-classic-items package (Nakroma).
// Usage: npm install wow-classic-items@2.0.1 somewhere, then
//   node make_data.js "<that folder>/node_modules/wow-classic-items" > RoleLoot/Data.lua
const path = require("path");
const pkg = process.argv[2];
const items = require(path.join(pkg, "data", "json", "data.json"));
const zones = new Map(require(path.join(pkg, "data", "json", "zones.json")).map((z) => [z.id, z]));
const check = (ok, msg) => { if (!ok) { console.error("FAILED: " + msg); process.exit(1); } };

const NOT_GEAR = new Set(["Non-equippable", "Bag", "Ammo", "Tabard", "Shirt"]);
const lua = (s) => '"' + String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"') + '"';
const rows = [];
for (const item of items) {
  const src = item.source;
  // Vanilla only (TBC and Wrath items have no content phase) and gear only.
  if (!(item.contentPhase >= 1 && item.contentPhase <= 6) || NOT_GEAR.has(item.slot) || !src) continue;
  let entry;
  if (src.category === "Boss Drop") {
    const zone = zones.get(src.zone);
    const instance = zone && (zone.category === "Dungeon" || zone.category === "Raid");
    entry = [lua(src.name), lua(zone ? zone.name : "World"), instance ? zone.level[0] : item.requiredLevel || Math.max(0, Math.min(60, item.itemLevel - 5))];
  } else if (src.category === "Zone Drop") { // (trash inside a dungeon or raid; world drops are skipped)
    const zone = zones.get(src.zone);
    if (!(zone && (zone.category === "Dungeon" || zone.category === "Raid"))) continue;
    entry = [lua("Trash Drops"), lua(zone.name), zone.level[0]];
  } else if (src.category === "Quest" && src.quests && src.quests.length) {
    const sides = new Set(src.quests.map((q) => q.faction));
    const side = sides.size === 1 && ["Alliance", "Horde"].includes([...sides][0]) ? [...sides][0] : null;
    // Quest rewards mostly have no required level (the quest has one): item level less 5 stands in.
    const level = item.requiredLevel || Math.max(0, Math.min(60, item.itemLevel - 5));
    entry = [lua("Quest"), lua(src.quests[0].name), level];
    if (side) entry.push(lua(side));
  } else continue;
  rows.push(`    [${item.itemId}] = { ${entry.join(", ")} },`);
}
check(rows.length > 5000, "only " + rows.length + " items");
process.stdout.write([
  "-- Generated by make_data.js from wow-classic-items (MIT, Nakroma). Do not edit by hand.",
  '-- itemID = { boss, or "Quest"; zone, or the quest name; lowest level; faction (quests only) }',
  "local _, ns = ...",
  "ns.SOURCES = {",
  ...rows,
  "}",
  "",
].join("\n"));
console.error(rows.length + " items");
